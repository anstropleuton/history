<#
.SYNOPSIS
    Recursively creates a README in every folder, listing that folder's files and
    subfolders with their earliest known date.

.DESCRIPTION
    - "Earliest date" = the oldest of Created, Modified and Accessed (the three
      timestamps NTFS stores). Copying a file resets Created but usually keeps
      Modified, so the oldest of the three is the best guess at the real age.
    - If README.md already exists in a folder (and wasn't made by this script),
      it writes README_FileIndex.md instead (then _2, _3, ...). Your own files
      are never overwritten.
    - Every file the script creates is recorded in .fileindex-manifest.json in
      the root folder. On re-run, the script updates those files in place
      instead of making new ones.
    - Use -Clean to delete everything listed in the manifest.

.EXAMPLE
    .\New-FileIndex.ps1                      # create / update indexes in current folder tree
    .\New-FileIndex.ps1 -Path "C:\Projects"  # a different folder
    .\New-FileIndex.ps1 -SortBy Name         # sort by name instead of date
    .\New-FileIndex.ps1 -Clean               # delete all generated files + manifest
#>
param(
    [string]$Path = ".",
    [ValidateSet("Date", "Name")]
    [string]$SortBy = "Date",
    [switch]$Clean
)

$root         = (Resolve-Path $Path).Path
$manifestPath = Join-Path $root ".fileindex-manifest.json"
$skipPattern  = '[\\/](\.git)([\\/]|$)'   # folders to skip (add e.g. node_modules: '(\.git|node_modules)')

# ---------- Load manifest (files generated by previous runs) ----------
$generated = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)
if (Test-Path $manifestPath) {
    $manifest = Get-Content $manifestPath -Raw | ConvertFrom-Json
    foreach ($rel in @($manifest.files)) {
        [void]$generated.Add((Join-Path $root ($rel -replace '/', '\')))
    }
}

# ---------- -Clean: delete generated files and manifest ----------
if ($Clean) {
    $removed = 0
    foreach ($f in $generated) {
        if (Test-Path $f) { Remove-Item $f -Force; Write-Host "Deleted $f"; $removed++ }
    }
    if (Test-Path $manifestPath) { Remove-Item $manifestPath -Force }
    Write-Host "Done. Deleted $removed generated file(s) and the manifest."
    return
}

# ---------- Collect folders up front ----------
$folders = @(Get-Item $root) + @(Get-ChildItem -Path $root -Recurse -Directory -Force |
    Where-Object { $_.FullName -notmatch $skipPattern })

$newManifestFiles = @()

foreach ($folder in $folders) {

    # Pick output file: reuse one we generated before, or use the first free name
    $candidates = @("README.md", "README_FileIndex.md") + (2..99 | ForEach-Object { "README_FileIndex_$_.md" })
    $outFile = $null
    foreach ($c in $candidates) {
        $full = Join-Path $folder.FullName $c
        if (-not (Test-Path $full) -or $generated.Contains($full)) { $outFile = $full; break }
    }
    if (-not $outFile) { Write-Warning "No free README name in $($folder.FullName), skipping."; continue }

    # Direct children only; skip .git, the manifest, and files we generated
    $items = Get-ChildItem -Path $folder.FullName -Force | Where-Object {
        $_.Name -ne ".git" -and
        $_.FullName -ne $manifestPath -and
        -not $generated.Contains($_.FullName) -and
        $_.FullName -ne $outFile
    }
    if (-not $items) { continue }   # nothing to list

    # Earliest of the timestamps Windows stores
    $rows = foreach ($item in $items) {
        $earliest = @($item.CreationTime, $item.LastWriteTime, $item.LastAccessTime) | Sort-Object | Select-Object -First 1
        [pscustomobject]@{
            Name     = $item.Name
            IsFolder = $item.PSIsContainer
            Date     = $earliest
        }
    }

    if ($SortBy -eq "Name") {
        $rows = $rows | Sort-Object @{Expression = { -not $_.IsFolder }}, Name
    } else {
        $rows = $rows | Sort-Object Date
    }

    $lines = @()
    $lines += "# $($folder.Name)"
    $lines += ""
    $lines += "> **Note:** These dates are not a definitive project start date. Each date is the oldest of the file's"
    $lines += "> created, modified and accessed timestamps, but copying, moving, downloading or restoring files from"
    $lines += "> backups could have change them."
    $lines += ""
    $lines += "_Generated on $(Get-Date -Format 'yyyy-MM-dd HH:mm')_"
    $lines += ""
    $lines += "| Name | Type | Earliest date |"
    $lines += "| --- | --- | --- |"

    foreach ($r in $rows) {
        $name = $r.Name -replace '\|', '\|'
        $type = "File"
        if ($r.IsFolder) { $name = "$name/"; $type = "Folder" }
        $lines += "| $name | $type | $($r.Date.ToString('yyyy-MM-dd HH:mm')) |"
    }

    Set-Content -Path $outFile -Value $lines -Encoding UTF8
    Write-Host "Wrote $outFile"
    $newManifestFiles += ($outFile.Substring($root.Length).TrimStart('\', '/') -replace '\\', '/')
}

# ---------- Save manifest ----------
$manifestObj = [ordered]@{
    updated = (Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
    root    = $root
    files   = @($newManifestFiles)
}
$manifestObj | ConvertTo-Json | Set-Content -Path $manifestPath -Encoding UTF8

Write-Host "Done. Wrote $($newManifestFiles.Count) index file(s). Manifest: $manifestPath"