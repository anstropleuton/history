#[derive(Clone)]
pub enum PrimitiveType {
    Int8,
    Int16,
    Int32,
    Int64,
    Int128,
    UInt8,
    UInt16,
    UInt32,
    UInt64,
    UInt128,
    // Float16,
    Float32,
    Float64,
    // Float128,
    // Float256,
    // Decimal32,
    // Decimal64,
    // Decimal128,
    Char,
    Bool,
    String,
}

impl PrimitiveType {
    pub fn from_str(s: &str) -> Option<PrimitiveType> {
        match s {
            "int8" => Some(PrimitiveType::Int8),
            "int16" => Some(PrimitiveType::Int16),
            "int32" => Some(PrimitiveType::Int32),
            "int64" => Some(PrimitiveType::Int64),
            "int128" => Some(PrimitiveType::Int128),
            "int" => Some(PrimitiveType::Int32),
            "uint8" => Some(PrimitiveType::UInt8),
            "uint16" => Some(PrimitiveType::UInt16),
            "uint32" => Some(PrimitiveType::UInt32),
            "uint64" => Some(PrimitiveType::UInt64),
            "uint128" => Some(PrimitiveType::UInt128),
            "uint" => Some(PrimitiveType::UInt32),
            "sint8" => Some(PrimitiveType::Int8),
            "sint16" => Some(PrimitiveType::Int16),
            "sint32" => Some(PrimitiveType::Int32),
            "sint64" => Some(PrimitiveType::Int64),
            "sint" => Some(PrimitiveType::Int32),
            // "float16" => Some(PrimitiveType::Float16),
            "float32" => Some(PrimitiveType::Float32),
            "float64" => Some(PrimitiveType::Float64),
            // "float128" => Some(PrimitiveType::Float128),
            // "float256" => Some(PrimitiveType::Float256),
            // "decimal32" => Some(PrimitiveType::Decimal32),
            // "decimal64" => Some(PrimitiveType::Decimal64),
            // "decimal128" => Some(PrimitiveType::Decimal128),
            // "decimal" => Some(PrimitiveType::Decimal32),
            "float" => Some(PrimitiveType::Float32),
            "char" => Some(PrimitiveType::Char),
            "bool" => Some(PrimitiveType::Bool),
            "string" => Some(PrimitiveType::String),
            _ => None,
        }
    }

    pub fn to_str(&self) -> &str {
        match self {
            PrimitiveType::Int8 => "int8",
            PrimitiveType::Int16 => "int16",
            PrimitiveType::Int32 => "int32",
            PrimitiveType::Int64 => "int64",
            PrimitiveType::Int128 => "int128",
            PrimitiveType::UInt8 => "uint8",
            PrimitiveType::UInt16 => "uint16",
            PrimitiveType::UInt32 => "uint32",
            PrimitiveType::UInt64 => "uint64",
            PrimitiveType::UInt128 => "uint128",
            // PrimitiveType::Float16 => "float16",
            PrimitiveType::Float32 => "float32",
            PrimitiveType::Float64 => "float64",
            // PrimitiveType::Float128 => "float128",
            // PrimitiveType::Float256 => "float256",
            // PrimitiveType::Decimal32 => "decimal32",
            // PrimitiveType::Decimal64 => "decimal64",
            // PrimitiveType::Decimal128 => "decimal128",
            PrimitiveType::Char => "char",
            PrimitiveType::Bool => "bool",
            PrimitiveType::String => "string",
        }
    }
}

pub enum PrimitiveValue {
    Int8(i8),
    Int16(i16),
    Int32(i32),
    Int64(i64),
    Int128(i128),
    UInt8(u8),
    UInt16(u16),
    UInt32(u32),
    UInt64(u64),
    UInt128(u128),
    // Float16(/* f16 */),
    Float32(f32),
    Float64(f64),
    // Float128(/* f128 */),
    // Float256(/* f256 */),
    // Decimal32(/* d32 */),
    // Decimal64(/* d64 */),
    // Decimal128(/* d128 */),
    Char(char),
    Bool(bool),
    String(Box<str>),
}
